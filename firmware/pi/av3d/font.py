GLYPH_W = 4.0
GLYPH_H = 6.0
ADVANCE = 6.0 # glyph width + gap

def strokes_for(text):
    strokes = []
    for i, ch in enumerate(text.upper()):
        if ch not in GLYPHS:
            raise ValueError(f"no glyph for {ch!r}; use A-Z, 0-9, space or - + . ! ? *")
        for stroke in GLYPHS[ch]:
            dx = i * ADVANCE
            strokes.append([(x + dx, y) for x, y in stroke])
    return strokes

def text_width_units(text):
    return max(len(text) * ADVANCE - (ADVANCE - GLYPH_W), 0.0)
